create or replace function public.create_store_order(
  p_customer_name text,
  p_customer_email text,
  p_channel text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_total integer := 0;
  v_items jsonb := '[]'::jsonb;
  v_reference text := 'FRAN6-' || upper(replace(gen_random_uuid()::text, '-', ''));
begin
  if p_channel is null or p_channel not in ('paystack', 'whatsapp') then
    raise exception 'Unsupported order channel';
  end if;
  if p_channel = 'paystack' and length(trim(coalesce(p_customer_name, ''))) not between 1 and 160 then
    raise exception 'Enter a valid customer name';
  end if;
  if p_channel = 'paystack' and (
    length(trim(coalesce(p_customer_email, ''))) not between 3 and 254
    or p_customer_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ) then
    raise exception 'Enter a valid customer email';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'An order must contain a list of items';
  end if;
  if jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'An order must contain at least one item';
  end if;
  if p_channel = 'paystack' and (
    auth.uid() is null
    or lower(coalesce(auth.jwt() ->> 'email', '')) <> lower(p_customer_email)
  ) then
    raise exception 'Sign in with the checkout email to pay by card';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item ->> 'id', '') !~ '^[0-9]+$'
      or coalesce(v_item ->> 'quantity', '') !~ '^[0-9]+$' then
      raise exception 'Invalid product or quantity';
    end if;

    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity not between 1 and 50 then
      raise exception 'Quantity must be between 1 and 50';
    end if;

    select * into v_product
    from public.products
    where id = (v_item ->> 'id')::integer
      and active = true
    for share;

    if not found then
      raise exception 'A selected product is no longer available';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'There is not enough stock for %', v_product.name;
    end if;

    v_total := v_total + v_product.price * v_quantity;
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'id', v_product.id,
      'name', v_product.name,
      'quantity', v_quantity,
      'price', v_product.price
    ));
  end loop;

  insert into public.orders (
    reference, customer_id, customer_name, customer_email, channel, status, total, items
  )
  values (
    v_reference,
    auth.uid(),
    coalesce(nullif(trim(p_customer_name), ''), 'WhatsApp customer'),
    lower(trim(coalesce(p_customer_email, ''))),
    p_channel,
    case when p_channel = 'paystack' then 'awaiting_payment' else 'whatsapp_requested' end,
    v_total,
    v_items
  );

  return jsonb_build_object('reference', v_reference, 'total', v_total);
end;
$$;

revoke all on function public.create_store_order(text, text, text, jsonb) from public;
grant execute on function public.create_store_order(text, text, text, jsonb) to anon, authenticated;

create or replace function public.confirm_store_order(
  p_reference text,
  p_transaction_id bigint,
  p_amount integer,
  p_email text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_item jsonb;
  v_updated integer;
begin
  select * into v_order
  from public.orders
  where reference = p_reference
  for update;
  if not found then
    raise exception 'Order reference was not found';
  end if;
  if p_amount <> v_order.total * 100
    or lower(coalesce(p_email, '')) <> lower(v_order.customer_email) then
    raise exception 'Payment details do not match the order';
  end if;
  if v_order.status in ('paid', 'processing', 'completed') then
    return true;
  end if;
  if v_order.status <> 'awaiting_payment' then
    raise exception 'Order is not awaiting payment';
  end if;

  for v_item in select value from jsonb_array_elements(v_order.items)
  loop
    update public.products
    set stock = stock - (v_item ->> 'quantity')::integer,
        updated_at = now()
    where id = (v_item ->> 'id')::integer
      and stock >= (v_item ->> 'quantity')::integer;
    get diagnostics v_updated = row_count;
    if v_updated <> 1 then
      raise exception 'Stock changed after payment was started; contact the store to resolve this order';
    end if;
  end loop;

  update public.orders
  set status = 'paid',
      paystack_transaction_id = p_transaction_id,
      updated_at = now()
  where id = v_order.id;
  return true;
end;
$$;

revoke all on function public.confirm_store_order(text, bigint, integer, text) from public;
grant execute on function public.confirm_store_order(text, bigint, integer, text) to service_role;

