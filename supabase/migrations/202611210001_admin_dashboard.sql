create table if not exists public.customer_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  full_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.sync_customer_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.customer_profiles (id, email, full_name)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', '')
  )
  on conflict (id) do update
  set email = excluded.email,
      full_name = excluded.full_name,
      updated_at = now();
  return new;
end;
$$;

drop trigger if exists sync_customer_profile_after_auth_change on auth.users;
create trigger sync_customer_profile_after_auth_change
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.sync_customer_profile();

insert into public.customer_profiles (id, email, full_name)
select id, coalesce(email, ''), coalesce(raw_user_meta_data ->> 'full_name', '')
from auth.users
on conflict (id) do update
set email = excluded.email,
    full_name = excluded.full_name,
    updated_at = now();

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  customer_id uuid references auth.users (id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  channel text not null check (channel in ('paystack', 'whatsapp')),
  status text not null check (
    status in ('whatsapp_requested', 'awaiting_payment', 'paid', 'processing', 'completed', 'cancelled')
  ),
  total integer not null check (total > 0),
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  paystack_transaction_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_customer_id_idx on public.orders (customer_id);

create or replace function public.is_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role' = 'admin', false);
$$;

